router.get("/stats", (req, res) => {
  const business = require("../config/business");
  const allMessages = db.getRecentMessages(5000);
  const incoming = allMessages.filter((m) => m.direction === "in");

  const totalMessages = allMessages.length;

  const hourCounts = new Array(24).fill(0);
  incoming.forEach((m) => {
    const h = new Date(m.created_at + "Z").getUTCHours();
    hourCounts[h] += 1;
  });
  let peakHour = 0;
  hourCounts.forEach((c, h) => {
    if (c > hourCounts[peakHour]) peakHour = h;
  });

  const uniqueContacts = new Set(incoming.map((m) => m.phone));
  const appointments = db.getAllUpcomingConfirmedAppointments();
  const allApptPhones = new Set(
    db.db.prepare("SELECT DISTINCT phone FROM appointments").all().map((r) => r.phone)
  );
  const contactsWithAppointment = [...uniqueContacts].filter((p) => allApptPhones.has(p));
  const bookedRatio = uniqueContacts.size
    ? Math.round((contactsWithAppointment.length / uniqueContacts.size) * 100)
    : 0;

  const productNames = (business.servicios || [])
    .map((s) => s.nombre)
    .concat(business.serviciosCotizacion || []);
  const productCounts = productNames.map((name) => {
    const keyword = name.split("(")[0].trim().split(" ").slice(0, 2).join(" ").toLowerCase();
    const count = incoming.filter((m) => (m.text || "").toLowerCase().includes(keyword)).length;
    return { name, count };
  }).filter((p) => p.count > 0).sort((a, b) => b.count - a.count);

  res.json({
    totalMessages,
    totalIncoming: incoming.length,
    peakHour,
    hourCounts,
    uniqueContacts: uniqueContacts.size,
    bookedContacts: contactsWithAppointment.length,
    bookedRatio,
    upcomingAppointments: appointments.length,
    topProducts: productCounts.slice(0, 6),
  });
});

router.get("/auto-clusters", (req, res) => {
  const allEntries = knowledge.getAllEntries();
  const clientEntries = allEntries.filter((e) => /^Cliente:/i.test(e.content || ""));
  const entries = allEntries.filter((e) => !/^Cliente:/i.test(e.content || ""));

  const clusters = [];
  if (clientEntries.length) {
    clusters.push({
      name: "Clientes",
      keyword: "cliente",
      noteIds: clientEntries.map((e) => e.id),
    });
  }

  const stop = new Set([
    "que","para","con","los","las","una","uno","del","por","sus","esta","esto","como","tiene",
    "pero","hace","muy","mas","son","fue","han","van","sin","hay","ser","este","eres","todo",
    "cada","cuando","donde","aqui","sobre","desde","hasta","entre","tambien","solo","bien",
    "parte","debe","puede","pueden","tiene","tener","haber","sido","sido","seran","sera",
    "crea","equipo","creativo","nota","notes",
  ]);
  // Count keyword frequency across all entries
  const freq = {};
  for (const e of entries) {
    const words = ((e.content || "") + " " + (e.title || ""))
      .toLowerCase().match(/[a-zà-ÿ]{4,}/g) || [];
    const unique = [...new Set(words.filter((w) => !stop.has(w)))];
    for (const w of unique) freq[w] = (freq[w] || 0) + 1;
  }
  // Top keywords appearing in ≥2 notes
  const topWords = Object.entries(freq)
    .filter(([, c]) => c >= 2)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 7)
    .map(([w]) => w);

  topWords.forEach((word) => {
    const noteIds = entries
      .filter((e) => ((e.content || "") + " " + (e.title || "")).toLowerCase().includes(word))
      .map((e) => e.id);
    if (noteIds.length >= 2) {
      clusters.push({
        name: word.charAt(0).toUpperCase() + word.slice(1),
        keyword: word,
        noteIds,
      });
    }
  });

  res.json(clusters);
});

router.post("/knowledge", express.json({ limit: "15mb" }), async (req, res) => {
  let content = (req.body?.content || "").trim();
  if (!content) return res.status(400).json({ error: "content requerido" });
  // Auto-tag: classify against existing templates if no hashtag already present
  if (!content.startsWith("#")) {
    try {
      const templates = knowledge.getAllTemplates();
      if (templates.length > 0) {
        const names = templates.map((t) => t.name).join(", ");
        const Anthropic = require("@anthropic-ai/sdk");
        const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
        const resp = await anthropic.messages.create({
          model: "claude-sonnet-4-6",
          max_tokens: 30,
          messages: [{
            role: "user",
            content: `Categorías disponibles: ${names}.\nNota: "${content}"\n¿A cuál categoría pertenece esta nota? Responde SOLO con el nombre exacto de la categoría (sin comillas, sin explicación). Si no encaja en ninguna, responde NONE.`,
          }],
        });
        const cat = (resp.content[0].text || "").trim();
        if (cat && cat !== "NONE" && templates.some((t) => t.name.toLowerCase() === cat.toLowerCase())) {
          const match = templates.find((t) => t.name.toLowerCase() === cat.toLowerCase());
          content = "#" + match.name.replace(/\s+/g, "") + " " + content;
        }
      }
    } catch (e) {
      console.error("auto-tag error:", e.message);
    }
  }
  const id = knowledge.addEntry(content, "manual");
  res.json({ id });
});

