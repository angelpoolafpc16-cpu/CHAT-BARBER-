// Dedicated endpoint to find-or-create a hub note for a template and append an entry.
// Avoids sending all notes to client and sidesteps any serialization issues.
router.post("/hub-save", express.json({ limit: "15mb" }), (req, res) => {
  try {
    const { templateName, entryContent } = req.body || {};
    if (!templateName || !entryContent) {
      return res.status(400).json({ error: "templateName y entryContent requeridos" });
    }
    const allNotes = knowledge.getAllNotes();
    let hub = allNotes.find(
      (n) =>
        (n.tags || []).includes("plantilla-hub") &&
        (n.title || "").toLowerCase() === templateName.toLowerCase()
    );
    if (!hub) {
      hub = knowledge.createNote({
        title: templateName,
        content: "",
        tags: [templateName, "plantilla-hub"],
        source: "manual",
      });
    }
    const stamp = new Date().toLocaleString("es-MX");
    const currentContent = sanitizeForJson(hub.content || "");
    const appended = (currentContent ? currentContent + "\n\n---\n" : "") + "[" + stamp + "] " + entryContent;
    knowledge.updateNote(hub.id, { content: appended });
    const hashtag = "#" + templateName.replace(/\s+/g, "");
    knowledge.addEntry(hashtag + " " + entryContent, "manual");
    res.json({ ok: true });
  } catch (err) {
    console.error("Error en hub-save:", err);
    res.status(500).json({ error: err.message || "Error desconocido" });
  }
});

